// Self-hosts third-party code and fonts so pages load from binchika.com only (faster on mobile networks,
// and still works if a CDN is blocked). Usage: node scripts/build-vendor.mjs [--fonts]
import { build } from "esbuild";
import { mkdir, copyFile, writeFile } from "node:fs/promises";

const OUT = "site/assets/vendor";
await mkdir(OUT, { recursive: true });
for (const [entry, name] of [["d3-world", "d3-world"], ["topojson", "topojson"], ["supabase", "supabase"], ["gsap", "gsap"]]) {
  const r = await build({ entryPoints: [`scripts/vendor/${entry}.js`], bundle: true, format: "esm", minify: true, target: "es2020", outfile: `${OUT}/${name}.js`, legalComments: "eof", metafile: true, logLevel: "warning" });
  const bytes = Object.values(r.metafile.outputs)[0].bytes;
  console.log(name, (bytes / 1024).toFixed(1), "KB");
}
await copyFile("node_modules/maplibre-gl/dist/maplibre-gl.js", `${OUT}/maplibre-gl.js`);
await copyFile("node_modules/maplibre-gl/dist/maplibre-gl.css", `${OUT}/maplibre-gl.css`);
console.log("maplibre-gl copied");

if (process.argv.includes("--fonts")) {
  // Google Fonts (OFL) → self-hosted woff2 + @font-face CSS. Latin + Latin-ext subsets only.
  const FAMILIES = "family=Atkinson+Hyperlegible:ital,wght@0,400;0,700;1,400&family=IBM+Plex+Mono:wght@400;500;600&family=Schibsted+Grotesk:wght@500;600;700;800;900&family=Unbounded:wght@700;900&display=swap";
  const UA = { headers: { "user-agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/131.0 Safari/537.36" } };
  let css = await (await fetch(`https://fonts.googleapis.com/css2?${FAMILIES}`, UA)).text();
  await mkdir(`${OUT}/fonts`, { recursive: true });
  // keep only latin / latin-ext blocks
  const blocks = css.split(/(?=\/\* )/).filter((b) => /\/\* (latin|latin-ext) \*\//.test(b));
  css = blocks.join("");
  let n = 0;
  for (const url of [...new Set(css.match(/https:\/\/fonts\.gstatic\.com\/[^)]+\.woff2/g) ?? [])]) {
    const file = url.split("/").slice(-2).join("-");
    await writeFile(`${OUT}/fonts/${file}`, Buffer.from(await (await fetch(url)).arrayBuffer()));
    css = css.replaceAll(url, `/assets/vendor/fonts/${file}`);
    n++;
  }
  await writeFile(`${OUT}/fonts.css`, `/* Self-hosted Google Fonts (SIL Open Font License). Generated by scripts/build-vendor.mjs */\n${css}`);
  console.log("fonts:", n, "woff2 files");
}
