// Loads the active tenant (one country) for the build and Node scripts: tenant_config.json → tenants/<id>/tenant.json.
// The build writes functions/_lib/tenant.generated.js (used by Pages Functions, the mailbox Worker and, copied, the
// browser) and site/data/locale.json from it. Schema: tenants/tenant.schema.json. Guide: docs/TENANT-CONFIG.md.
import { readFileSync } from "node:fs";

const REQUIRED = ["id", "country", "iso", "domain", "locale", "electoralBody", "notice", "site", "geography", "pollingUnits", "parties", "races", "resultForm", "rules"];

/** @returns {object} the tenant, checked for the fields the code reads. Throws with a plain message if one is missing. */
export function loadTenant(root = ".") {
  const { tenant } = JSON.parse(readFileSync(`${root}/tenant_config.json`, "utf8"));
  if (!/^[a-z_]{2,20}$/.test(String(tenant ?? ""))) throw new Error(`tenant_config.json: "tenant" must name a folder under tenants/ (got ${JSON.stringify(tenant)})`);
  const t = JSON.parse(readFileSync(`${root}/tenants/${tenant}/tenant.json`, "utf8"));
  const missing = REQUIRED.filter((k) => t[k] === undefined);
  for (const [k, sub] of [["locale", ["timeZone", "zoneLabel", "utcOffset", "city", "lang"]], ["electoralBody", ["name", "short"]], ["site", ["origin", "sourceRepo"]], ["pollingUnits", ["total", "totalSource", "codePattern", "statePrefix"]]])
    for (const s of sub) if (t[k]?.[s] === undefined) missing.push(`${k}.${s}`);
  if (missing.length) throw new Error(`tenants/${tenant}/tenant.json is missing: ${missing.join(", ")}`);
  if (JSON.stringify(t).includes("FILL")) throw new Error(`tenants/${tenant}/tenant.json still has FILL placeholders`);
  return t;
}

/** The generated ES module (same text everywhere it is copied). */
export const tenantModule = (t) => `// Generated by scripts/build-site.mjs from tenant_config.json → tenants/${t.id}/tenant.json. Do not edit: change the tenant and rebuild.
export const TENANT = ${JSON.stringify(t, null, 2)};
export default TENANT;
`;

/** site/data/locale.json, read by site.js for the header clock (unchanged format). */
export const localeJson = (t) => `${JSON.stringify({ country: t.iso, countryName: t.country, timeZone: t.locale.timeZone, zoneLabel: t.locale.zoneLabel, utcOffset: t.locale.utcOffset, city: t.locale.city, locale: t.locale.lang }, null, 2)}\n`;
