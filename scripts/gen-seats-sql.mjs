// Generated supabase/migrations/0004_seats.sql (applied; do not regenerate it): SZV-001…111, 3 per state + FCT, A–Z.
// Seats added later live in their own migrations, e.g. 0010_szv_recalibration.sql (SZV-112…129).
// Original note: sequential seat codes for SZV (3 per state + FCT, A–Z by state)
// and NRV (3 per region, R1…R8), seat↔verifier binding rules and a public seat board.
import { readFile, writeFile } from "node:fs/promises";
const meta = JSON.parse(await readFile("site/data/states.json", "utf8"));
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const rows = [];
let n = 0;
for (const s of [...meta.states].sort((a, b) => a.name.localeCompare(b.name, "en-GB"))) {
  const region = meta.verifierRegions.regions.find((r) => r.states.includes(s.iso)).id;
  for (let k = 1; k <= 3; k++) { n++; rows.push(`(${q(`SZV-${String(n).padStart(3, "0")}`)}, 'szv', ${q(s.iso)}, ${q(region)}, ${n}, ${q(`${s.short ?? s.name} seat ${k}`)})`); }
}
let m = 0;
for (const r of meta.verifierRegions.regions) for (let k = 1; k <= 3; k++) { m++; rows.push(`(${q(`NRV-${String(m).padStart(2, "0")}`)}, 'nrv', null, ${q(r.id)}, ${m}, ${q(`${r.id} ${r.name} seat ${k}`)})`); }

const sql = `-- Sequential verifier seats (generated by scripts/gen-seats-sql.mjs). Builds forward on 0001–0003.
-- SZV-001…SZV-111: 3 per state + FCT, states A–Z. NRV-01…NRV-24: 3 per region (odd, so no tied regional votes).
create table if not exists public.verifier_seats (
  code text primary key,
  role text not null check (role in ('szv','nrv')),
  state_iso text references public.ng_states(iso),
  region_id text not null references public.verifier_regions(id),
  ordinal int not null,
  label text not null,
  check ((role = 'szv' and state_iso is not null) or (role = 'nrv' and state_iso is null))
);
insert into public.verifier_seats (code, role, state_iso, region_id, ordinal, label) values
${rows.join(",\n")}
on conflict (code) do update set role = excluded.role, state_iso = excluded.state_iso, region_id = excluded.region_id, ordinal = excluded.ordinal, label = excluded.label;

alter table public.verifiers add column if not exists seat_code text unique references public.verifier_seats(code);

-- A seat must match the verifier's role and area (SZV: same state; NRV: same region).
create or replace function public.enforce_seat() returns trigger language plpgsql as $$
declare s record;
begin
  if new.seat_code is null then return new; end if;
  select * into s from public.verifier_seats where code = new.seat_code;
  if s.role <> new.role then raise exception 'seat % is for %, not %', s.code, s.role, new.role; end if;
  if s.role = 'szv' and s.state_iso is distinct from new.state_iso then raise exception 'seat % belongs to %', s.code, s.state_iso; end if;
  if s.role = 'nrv' and s.region_id is distinct from new.region_id then raise exception 'seat % belongs to region %', s.code, s.region_id; end if;
  return new;
end $$;
drop trigger if exists trg_seat on public.verifiers;
create trigger trg_seat before insert or update of seat_code, role, state_iso, region_id on public.verifiers for each row execute function public.enforce_seat();

-- Public seat board: code, area and whether it is taken. Never who holds it.
create or replace view public.seat_board with (security_invoker = false) as
  select s.code, s.role, s.state_iso, s.region_id, s.ordinal, s.label,
         exists (select 1 from public.verifiers v where v.seat_code = s.code and v.active) as taken
  from public.verifier_seats s;
alter table public.verifier_seats enable row level security;
drop policy if exists "public read seats" on public.verifier_seats;
create policy "public read seats" on public.verifier_seats for select using (true);
grant select on public.verifier_seats, public.seat_board to anon, authenticated;
revoke insert, update, delete on public.verifier_seats from anon, authenticated;
`;
await writeFile("supabase/migrations/0004_seats.sql", sql);
console.log("seats:", n, "SZV +", m, "NRV");
