// Prepared, not live: writes src/critical/home.css, the CSS rules that style the home page above and including the hero
// (INEC notice, masthead, hero) at 390 / 768 / 1280 px in light and dark. build-site.mjs inlines it only when run with
// CRITICAL_CSS=1, and only while the recorded hash still matches fonts.css + main.css + v3.css; otherwise it keeps the
// normal render-blocking stylesheets. Measured on a preview (28 Oct 2026): LCP about 0.43 s sooner in Chrome. It relies on
// Chrome not painting content after a <body> stylesheet; other browsers may briefly show that content unstyled, so test
// Firefox and Safari before switching it on. Usage: node scripts/build-site.mjs && node scripts/build-critical-css.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const puppeteer = require("puppeteer-core");

export const CSS_FILES = ["site/assets/vendor/fonts.css", "site/assets/css/main.css", "site/assets/css/v3.css"];
export const cssHash = () => createHash("sha256").update(CSS_FILES.map((f) => readFileSync(f, "utf8")).join("\n")).digest("hex");

if (import.meta.url === `file:///${process.argv[1].replace(/\\/g, "/")}`) {
  const ORIGIN = "http://critical.invalid";
  const TYPES = { html: "text/html", css: "text/css", js: "text/javascript", json: "application/json", woff2: "font/woff2", svg: "image/svg+xml", webp: "image/webp", png: "image/png" };
  const browser = await puppeteer.launch({ executablePath: process.env.CHROME_PATH ?? "C:/Program Files/Google/Chrome/Application/chrome.exe", headless: true });
  const keep = new Map();
  for (const [w, h] of [[390, 844], [768, 1024], [1280, 900]]) for (const scheme of ["light", "dark"]) {
    const page = await browser.newPage();
    await page.setRequestInterception(true);
    page.on("request", (req) => {
      const u = new URL(req.url());
      if (u.origin !== ORIGIN) return req.respond({ status: 204, body: "" }); // no network: analytics, APIs
      const p = u.pathname.endsWith("/") ? `site${u.pathname}index.html` : `site${u.pathname}`;
      try { req.respond({ status: 200, contentType: TYPES[p.split(".").pop()] ?? "application/octet-stream", body: readFileSync(p) }); } catch { req.respond({ status: 404, body: "" }); }
    });
    await page.setViewport({ width: w, height: h, isMobile: w < 700 });
    await page.emulateMediaFeatures([{ name: "prefers-color-scheme", value: scheme }]);
    await page.goto(`${ORIGIN}/`, { waitUntil: "load" });
    const got = await page.evaluate(() => {
      const hero = document.querySelector("section.hero");
      const els = [document.documentElement, document.body];
      for (const el of document.body.querySelectorAll("*")) { if (hero.compareDocumentPosition(el) & Node.DOCUMENT_POSITION_FOLLOWING && !hero.contains(el)) continue; els.push(el); }
      const strip = (s) => s.replace(/::?(before|after|placeholder|selection|marker|backdrop|-webkit-[\w-]+|-moz-[\w-]+)\b/g, "").replace(/:(hover|focus|focus-visible|focus-within|active|visited|checked|disabled|target)\b/g, "") || "*";
      const matches = (sel) => sel.split(",").some((s) => { try { const t = strip(s.trim()); return els.some((e) => e.matches(t)); } catch { return false; } });
      const res = {};
      const walk = (rules, path, wrap) => [...rules].forEach((r, i) => {
        const p = `${path}.${String(i).padStart(4, "0")}`;
        if (r instanceof CSSStyleRule) { if (r.selectorText.startsWith(":root") || matches(r.selectorText)) res[p] = { wrap, text: r.cssText }; }
        else if (r instanceof CSSMediaRule) walk(r.cssRules, p, [...wrap, `@media ${r.conditionText}`]);
        else if (r instanceof CSSSupportsRule) walk(r.cssRules, p, [...wrap, `@supports ${r.conditionText}`]);
        else if (r instanceof CSSFontFaceRule || r instanceof CSSKeyframesRule) res[p] = { wrap, text: r.cssText };
      });
      [...document.styleSheets].forEach((s, i) => { if (s.href?.startsWith(location.origin)) walk(s.cssRules, `s${i}`, []); });
      return res;
    });
    for (const [k, v] of Object.entries(got)) keep.set(k, v);
    await page.close();
  }
  await browser.close();
  const css = [...keep.keys()].sort().map((k) => { const { wrap, text } = keep.get(k); return wrap.reduceRight((acc, w) => `${w}{${acc}}`, text); }).join("\n");
  mkdirSync("src/critical", { recursive: true });
  writeFileSync("src/critical/home.css", `/* generated by scripts/build-critical-css.mjs; sources-sha256: ${cssHash()} */\n${css}\n`);
  console.log(`src/critical/home.css: ${keep.size} rules, ${css.length} bytes`);
}
